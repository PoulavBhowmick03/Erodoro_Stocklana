// Generate the shared error table the IDLs do not carry.
//
// `series`, `factory` and `oracle_adapter` all return `common::OptionsError`,
// which is declared in the `common` crate rather than in any of them. Anchor
// emits an IDL `errors` array only for errors declared in the program's own
// crate, so all three ship with an empty one — and a client has no way to turn
// `custom program error: 0x1793` into "the series is paused".
//
// Only `market` has its own `#[error_code]` enum, which is why it is the one
// program whose IDL does carry error messages.
//
// This reads `common/src/error.rs` and emits the table. Ordering is what
// assigns the codes: Anchor numbers variants by declaration order from 6000, so
// the position of each variant *is* its code, and inserting one anywhere but
// the end renumbers everything after it. The generated file is committed, and
// CI regenerates it and fails on a diff, which is what makes that renumbering
// loud instead of silent.
//
//   node web/scripts/gen-error-table.mjs [--check]

import fs from "fs";
import path from "path";

const root = path.resolve(import.meta.dirname, "..", "..");
const SOURCE = path.join(root, "common", "src", "error.rs");
// Emitted as TypeScript rather than JSON so it imports the same way from the
// bundler and from plain Node. A `.json` import needs `with { type: "json" }`
// under Node's ESM loader and does not under Next's, which makes the table
// untestable outside the app for no benefit.
const OUT = path.join(root, "web", "lib", "error-table.ts");

/** Anchor reserves 6000..=6999 for user-defined errors. */
const BASE = 6000;

const src = fs.readFileSync(SOURCE, "utf8");

// `market`'s own table, taken from the IDL it does carry.
const marketErrors = (
  JSON.parse(fs.readFileSync(path.join(root, "web", "lib", "idl", "market.json"), "utf8"))
    .errors ?? []
).map((e) => ({ code: e.code, name: e.name, msg: e.msg }));

// Everything between the enum's opening brace and its closing one. Parsing the
// file rather than the compiled artifact keeps this honest: the source is what
// defines the order.
const body = src.slice(src.indexOf("pub enum OptionsError {"));
const end = body.indexOf("\n}");
if (end < 0) throw new Error("could not find the end of OptionsError");

const entries = [];
let pendingMsg = null;
for (const raw of body.slice(0, end).split("\n")) {
  const line = raw.trim();
  const msg = line.match(/^#\[msg\("(.*)"\)\]$/);
  if (msg) {
    pendingMsg = msg[1];
    continue;
  }
  const variant = line.match(/^([A-Z][A-Za-z0-9]*),$/);
  if (variant) {
    entries.push({
      code: BASE + entries.length,
      name: variant[1],
      msg: pendingMsg ?? variant[1],
    });
    pendingMsg = null;
  }
}

if (entries.length === 0) {
  console.error("parsed zero variants — the enum's shape must have changed");
  process.exit(1);
}

const json =
  "// SPDX-License-Identifier: Apache-2.0\n" +
  "//\n" +
  "// GENERATED by web/scripts/gen-error-table.mjs from common/src/error.rs.\n" +
  "// Do not edit. CI regenerates this and fails on a diff.\n" +
  "//\n" +
  "// Anchor numbers `#[error_code]` variants from 6000 by declaration order, so\n" +
  "// each variant's position *is* its code. Inserting one anywhere but the end\n" +
  "// renumbers everything after it, which is why this file is checked rather\n" +
  "// than trusted.\n\n" +
  "export type SharedError = { code: number; name: string; msg: string };\n\n" +
  "export const SHARED_ERRORS: SharedError[] = " +
  JSON.stringify(entries, null, 2) +
  ";\n\n" +
  "// `market` declares its own `#[error_code]` enum, so Anchor *does* emit an\n" +
  "// IDL table for it -- and its codes start at 6000 too, which means they\n" +
  "// collide with the shared ones. Which table applies depends on which program\n" +
  "// threw. Copied here so nothing has to import JSON, which needs an import\n" +
  "// attribute under Node's ESM loader and none under the bundler.\n" +
  "export const MARKET_ERRORS: SharedError[] = " +
  JSON.stringify(marketErrors, null, 2) +
  ";\n";

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing !== json) {
    console.error(
      `${path.relative(root, OUT)} is stale. Run 'node web/scripts/gen-error-table.mjs'.\n` +
        "If a variant moved, every code after it changed — which is why this fails loudly.",
    );
    process.exit(1);
  }
  console.log(`error table matches common/src/error.rs (${entries.length} variants)`);
  process.exit(0);
}

fs.writeFileSync(OUT, json);
console.log(`wrote ${path.relative(root, OUT)} — ${entries.length} variants, ${BASE}..${BASE + entries.length - 1}`);
