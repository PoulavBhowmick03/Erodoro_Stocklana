// Generate the landing page's deployment facts from the deployment manifest.
//
// The landing route is static: no wallet, no RPC, no chain read (see
// `web/README.md`). That is worth keeping -- it is the one page that must
// render for someone on a phone on hotel wifi with no extension installed.
//
// But a page that says nothing verifiable is a brochure. `deployments/*.json`
// already records what is actually deployed: program ids, the genesis hash the
// app checks against, the MagicBlock validator, how many books are registered,
// and -- importantly -- what does *not* work yet. All of it is true at build
// time and none of it needs a request.
//
// So the ticker and the "Verify it yourself" block read from here. Emitting a
// module rather than importing the JSON directly keeps the landing page from
// depending on a path outside `web/`, and lets this file carry the one thing
// the manifest does not: which cluster the current build is for.
//
//   node web/scripts/gen-deployment-facts.mjs [--check]

import fs from "fs";
import path from "path";

const root = path.resolve(import.meta.dirname, "..", "..");
const OUT = path.join(root, "web", "lib", "deployment-facts.ts");

const clusters = ["devnet", "mainnet"];

const read = (cluster) =>
  JSON.parse(fs.readFileSync(path.join(root, "deployments", `${cluster}.json`), "utf8"));

/**
 * The programs a reader can look up, in the order they matter to someone
 * trying to check the claim rather than in the order the manifest lists them.
 */
const PROGRAM_ORDER = [
  ["series", "Series", "Splits collateral into P and N, and settles them"],
  ["factory", "Factory", "The registry that makes a series canonical"],
  ["market", "Market", "The order book"],
  ["manifest", "Manifest", "The CLOB the live books run on"],
  ["oracle_adapter", "Oracle adapter", "Reads the Pyth price settlement uses"],
  ["ephemeral_spl_token", "Ephemeral SPL", "Token custody inside a live session"],
];

function facts(cluster) {
  const m = read(cluster);
  const programs = PROGRAM_ORDER.filter(([key]) => m.programs?.[key]).map(
    ([key, label, purpose]) => ({ key, label, purpose, address: m.programs[key] }),
  );
  return {
    cluster: m.cluster,
    ready: Boolean(m.ready),
    updatedAt: m.updatedAt ?? null,
    genesisHash: m.genesisHash ?? null,
    quoteMint: m.quoteMint ?? null,
    programs,
    magicblock: {
      validator: m.magicblock?.validator ?? null,
      registeredBooks: m.magicblock?.registeredBooks ?? 0,
      trading: m.magicblock?.trading ?? null,
      // Stated rather than omitted. This is the one thing on the page that
      // says what the protocol cannot do yet, and it is the reason the
      // Portfolio withholds its return-to-wallet control.
      settlementExit: m.magicblock?.settlementExit ?? null,
    },
  };
}

const built = Object.fromEntries(clusters.map((c) => [c, facts(c)]));

const source =
  "// Generated by web/scripts/gen-deployment-facts.mjs. Do not edit.\n" +
  "//\n" +
  "// Sourced from deployments/*.json so the landing page can state what is\n" +
  "// deployed without making a request. `prebuild` re-runs the generator with\n" +
  "// --check, so a redeploy that is not reflected here fails the build.\n\n" +
  "export type DeployedProgram = {\n" +
  "  key: string;\n" +
  "  label: string;\n" +
  "  purpose: string;\n" +
  "  address: string;\n" +
  "};\n\n" +
  "export type DeploymentFacts = {\n" +
  "  cluster: string;\n" +
  "  ready: boolean;\n" +
  "  updatedAt: string | null;\n" +
  "  genesisHash: string | null;\n" +
  "  quoteMint: string | null;\n" +
  "  programs: DeployedProgram[];\n" +
  "  magicblock: {\n" +
  "    validator: string | null;\n" +
  "    registeredBooks: number;\n" +
  "    trading: string | null;\n" +
  "    settlementExit: string | null;\n" +
  "  };\n" +
  "};\n\n" +
  "export const DEPLOYMENTS: Record<string, DeploymentFacts> = " +
  JSON.stringify(built, null, 2) +
  ";\n";

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing !== source) {
    console.error(
      `${path.relative(root, OUT)} is stale. Run 'node web/scripts/gen-deployment-facts.mjs'.\n` +
        "The landing page states these addresses as fact, so a redeploy that is not\n" +
        "reflected here would have the site vouching for the wrong programs.",
    );
    process.exit(1);
  }
  console.log(`deployment facts match deployments/ (${clusters.length} clusters)`);
  process.exit(0);
}

fs.writeFileSync(OUT, source);
const n = built.devnet.programs.length;
console.log(`wrote ${path.relative(root, OUT)} — ${clusters.length} clusters, ${n} devnet programs`);
